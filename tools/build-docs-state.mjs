#!/usr/bin/env node
/**
 * Keep the documentation's *state* sections true, by deriving them.
 *
 *   node tools/build-docs-state.mjs           # rewrite the blocks in place
 *   node tools/build-docs-state.mjs --check   # exit 1 if stale (for CI)
 *
 * WHY THIS EXISTS
 * ---------------
 * Docs rot because someone has to remember to update them, and the failure mode
 * this project is built against is not malice, it is a busy Tuesday. So the same
 * rule applies here as everywhere else: derived, never duplicated.
 *
 * The durable parts of OVERVIEW.md and OPERATIONS.md (architecture, principles,
 * the runbook) are written by hand and stay written. Only the volatile parts —
 * counts, statuses, which components exist yet — are generated, and they are
 * generated from the repository itself, so they cannot disagree with reality.
 *
 * Content between these markers is REPLACED on every run. Do not hand-edit:
 *
 *     <!-- STATE:BEGIN --> ... <!-- STATE:END -->
 *
 * WHAT THIS DELIBERATELY DOES NOT DO
 * ----------------------------------
 * Some facts live in dashboards we cannot see: whether Netlify builds are
 * enabled, whether the Buttondown signup has been tested, what was agreed with
 * a reviewer. Inventing those would be worse than omitting them. They stay
 * hand-maintained inside a MANUAL block, each with a "confirmed on" date, so
 * that stale human knowledge is *visible as stale* rather than silently wrong.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(process.env.BANK_ROOT ?? ".");
const CHECK = process.argv.includes("--check");
const BEGIN = "<!-- STATE:BEGIN -->";
const END = "<!-- STATE:END -->";

const read = (p) => readFileSync(join(ROOT, p), "utf8");
const has = (p) => existsSync(join(ROOT, p));

/* ---------- derive the facts ---------- */

const entries = readdirSync(join(ROOT, "bank"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(readFileSync(join(ROOT, "bank", f), "utf8")));

const status = {};
for (const e of entries) status[e.review.status] = (status[e.review.status] ?? 0) + 1;
const active = entries.filter((e) => e.review.status !== "retired");
const approved = status.approved ?? 0;

const cefr = {};
for (const e of active) cefr[e.cefr] = (cefr[e.cefr] ?? 0) + 1;
const b1b2 = Math.round((((cefr.B1 ?? 0) + (cefr.B2 ?? 0)) / active.length) * 100);

let candidates = 0;
try { candidates = (read("CANDIDATES.md").match(/^\|/gm) ?? []).length; } catch {}

let alternatives = 0, altRejected = 0;
try {
  const a = JSON.parse(read("alternatives.json")).alternatives ?? [];
  alternatives = a.length;
  altRejected = a.filter((x) => x.status === "rejected").length;
} catch {}

let reviewers = [];
try {
  const r = JSON.parse(read("reviewers.json")).people ?? {};
  reviewers = Object.entries(r).map(([id, p]) => `${id} (${(p.lang ?? []).join("/")})`);
} catch {}

const tools = readdirSync(join(ROOT, "tools")).filter((f) => f.endsWith(".mjs")).sort();

// component existence — the questions people actually ask
const components = [
  ["Email renderer", has("tools/build-email.mjs")],
  ["Landing page builder", has("tools/build-landing.mjs")],
  ["Social card builder", has("tools/build-social.mjs")],
  ["Teaser builder", has("tools/build-teaser.mjs")],
  ["Archive backfill", has("tools/build-archive.mjs")],
  ["Scheduler", has("tools/schedule.mjs")],
  ["Validator", has("tools/validate.mjs")],
  ["Netlify config", has("netlify.toml")],
  ["CI workflows", has(".github/workflows/validate.yml")],
];

// detectable staleness — things we CAN check
const warnings = [];
try {
  const brand = JSON.parse(read("brand.json"));
  const handles = brand?.social?.handles;
  if (!handles || Object.keys(handles).length === 0) {
    warnings.push("`brand.json` has no `social.handles` — generators cannot cite handles consistently.");
  }
} catch { warnings.push("`brand.json` unreadable."); }

if (approved === 0) {
  warnings.push(`**0 of ${active.length} entries approved** — nothing may legitimately ship to a reader.`);
}
if (!has("tools/build-email.mjs")) {
  warnings.push("Email renderer not built — the newsletter cannot send.");
}

const today = new Date().toISOString().slice(0, 10);

/* ---------- render the block ---------- */

const block = `${BEGIN}
<!-- GENERATED by tools/build-docs-state.mjs — do not hand-edit. Run the tool. -->

*State derived from the repository on ${today}.*

### Content

| | |
|---|---|
| Entries in bank | **${entries.length}** (${active.length} active, ${status.retired ?? 0} retired) |
| By status | ${Object.entries(status).map(([k, v]) => `${k}: ${v}`).join(" · ")} |
| **Approved and shippable** | **${approved}** |
| CEFR mix (active) | ${Object.entries(cefr).sort().map(([k, v]) => `${k}: ${v}`).join(" · ")} — B1+B2 = ${b1b2}% |
| Sketched in queue | ~${candidates} |
| Alternative pairings | ${alternatives} (${altRejected} rejected) |
| Allowlisted reviewers | ${reviewers.length ? reviewers.join(", ") : "none"} |

### Components

| Component | Built |
|---|---|
${components.map(([n, ok]) => `| ${n} | ${ok ? "yes" : "**no**"} |`).join("\n")}

Tooling: ${tools.length} generators in \`tools/\`.

### Automatically detected issues

${warnings.length ? warnings.map((w) => `- ${w}`).join("\n") : "- none"}

${END}`;

/* ---------- inject ---------- */

const targets = ["OVERVIEW.md", "OPERATIONS.md"].filter(has);
let stale = [];

for (const file of targets) {
  const src = read(file);
  if (!src.includes(BEGIN) || !src.includes(END)) {
    console.log(`  ${file}: no STATE markers — skipped (add ${BEGIN} / ${END} to enable)`);
    continue;
  }
  const next = src.replace(new RegExp(`${BEGIN}[\\s\\S]*?${END}`), block);
  // compare ignoring the generated date line, so a rerun on a later day is not "stale"
  const strip = (s) => s.replace(/\*State derived from the repository on \d{4}-\d{2}-\d{2}\.\*/, "");
  if (strip(next) !== strip(src)) {
    if (CHECK) stale.push(file);
    else { writeFileSync(join(ROOT, file), next); console.log(`  ${file} ← state refreshed`); }
  } else if (!CHECK) {
    console.log(`  ${file} — already current`);
  }
}

if (CHECK) {
  if (stale.length) {
    console.error(`STALE DOCS — ${stale.join(", ")} disagree with the repository.`);
    console.error("Run: node tools/build-docs-state.mjs");
    process.exit(1);
  }
  console.log("Docs state is current.");
}
